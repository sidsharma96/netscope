"""Copy question-bank entries into each teaching chapter's closing section.

The question bank in docs/questions/ is the single source. Each question
carries a tag line such as `<!-- chapters: 30-putting-bytes-in-order -->`.
An additional `exercise` tag explicitly selects a question for a chapter.
Topic tags alone never place advanced questions into an introductory lesson.
Run it after editing the bank; check_docs.py fails when a chapter is out of date.

    python3 scripts/sync_questions.py
"""
from pathlib import Path
import re
import sys

from doclinks import slug as heading_slug

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'docs'
LEVELS = ['newcomer', 'practitioner', 'expert']
MARKER = '<!-- check-your-understanding: generated by scripts/sync_questions.py from docs/questions; edit the bank, not this section -->'
TAG = re.compile(r'^<!-- chapters: ([a-z0-9, -]+) -->$', re.MULTILINE)
EXERCISE = re.compile(r'^<!-- exercise: ([a-z0-9, -]+) -->$', re.MULTILINE)
MIN_QUESTIONS, MAX_QUESTIONS = 1, 3

# Chapters that teach a mechanism and therefore end with questions. The
# orientation, walkthrough and writing chapters do not.
TEACHING = [
    '22-running-a-program', '02-reading-a-capture', '07-values-and-functions',
    '03-storing-requests', '08-structs-vectors-and-ids', '09-options-results-and-matching',
    '10-importing-a-har', '39-opening-large-captures', '37-keeping-your-place', '11-drawing-and-navigation', '38-leaving-the-terminal-usable', '12-grouping-requests', '40-counting-grouping-work',
    '13-following-redirects', '14-recognizing-repeats', '41-finding-follow-ups-quickly', '15-reading-protocol-labels',
    '16-preparing-a-request', '17-waiting-for-a-response', '24-sharing-work', '42-locks-and-atomics',
    '18-comparing-responses', '19-submitting-text', '21-moving-through-text',
    '25-reading-event-streams', '26-switching-protocols', '27-observing-live-events',
    '28-sharing-a-connection', '29-reading-packet-bytes', '30-putting-bytes-in-order', '43-reading-a-coverage-map',
    '31-finding-http-boundaries', '32-reading-signaling', '33-interpreting-a-trace',
    '20-remembering-a-request', '23-shaping-the-program', '04-quality-and-tests',
    '34-defending-the-design',
    '36-investigating-a-slow-operation',
]


def questions(level):
    """Return (title, tags, text) for each question on one bank page."""
    text = (DOCS / 'questions' / f'{level}.md').read_text()
    blocks = re.split(r'^(?=### )', text, flags=re.MULTILINE)[1:]
    result = []
    for block in blocks:
        block = re.split(r'^(?=## )', block, flags=re.MULTILINE)[0].rstrip()
        title = block.splitlines()[0][4:].strip()
        tag = TAG.search(block)
        tags = [t.strip() for t in tag[1].split(',')] if tag else []
        result.append((title, tags, block))
    return result


def exercise_tags(block):
    """Return the chapters whose prerequisites this question was reviewed against."""
    tag = EXERCISE.search(block)
    return [t.strip() for t in tag[1].split(',')] if tag else []


def selection(slug, bank):
    """Use explicit editorial choices; difficulty labels do not select exercises."""
    return [q for level in LEVELS for q in bank[level] if slug in exercise_tags(q[2])]


def section(chosen, further):
    parts = [
        MARKER,
        '## Check your understanding',
        'Try these questions using the explanation above, then open the answers.',
    ]
    for _, _, block in chosen:
        clean = EXERCISE.sub('', TAG.sub('', block))
        clean = re.sub(r'^\*\*Level:\*\* .*\n', '', clean, flags=re.MULTILINE)
        parts.append(re.sub(r'\n{3,}', '\n\n', clean).strip())
    if further:
        parts.append('<details>\n<summary>Further questions for later study</summary>')
        for level, title in further:
            anchor = heading_slug(title)
            parts.append(f'<a id="{anchor}"></a>\n\n'
                         f'[{title}](../questions/{level}.md#{anchor})')
        parts.append('</details>')
    return '\n\n'.join(parts) + '\n'


def expected(path, bank):
    text = path.read_text()
    body = text.split(MARKER)[0].rstrip() + '\n'
    chosen = selection(path.stem, bank)
    titles = {q[0] for q in chosen}
    # Keep old question links useful without presenting advanced material as homework.
    further = [(level, q[0]) for level in LEVELS for q in bank[level]
               if path.stem in q[1] and q[0] not in titles]
    return body + '\n' + section(chosen, further)


def bank():
    return {level: questions(level) for level in LEVELS}


def main():
    loaded = bank()
    for slug in TEACHING:
        path = DOCS / 'chapters' / f'{slug}.md'
        path.write_text(expected(path, loaded))
        count = len(selection(slug, loaded))
        note = '' if count >= MIN_QUESTIONS else f'  (fewer than {MIN_QUESTIONS})'
        print(f'{slug}: {count} questions{note}')


if __name__ == '__main__':
    sys.exit(main())
