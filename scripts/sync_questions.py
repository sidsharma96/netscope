"""Copy question-bank entries into each teaching chapter's closing section.

The question bank in docs/questions/ is the single source. Each question
carries a tag line such as `<!-- chapters: 30-putting-bytes-in-order -->`.
This script gives every teaching chapter a generated "Check your
understanding" section holding up to five tagged questions, taken in turn
from the newcomer, practitioner and expert pages. Run it after editing the
bank; check_docs.py fails when a chapter is out of date.

    python3 scripts/sync_questions.py
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'docs'
LEVELS = ['newcomer', 'practitioner', 'expert']
MARKER = '<!-- check-your-understanding: generated by scripts/sync_questions.py from docs/questions; edit the bank, not this section -->'
TAG = re.compile(r'^<!-- chapters: ([a-z0-9, -]+) -->$', re.MULTILINE)
MIN_QUESTIONS, MAX_QUESTIONS = 3, 5

# Chapters that teach a mechanism and therefore end with questions. The
# orientation, walkthrough, design-defense and writing chapters do not.
TEACHING = [
    '22-running-a-program', '02-reading-a-capture', '07-values-and-functions',
    '03-storing-requests', '08-structs-vectors-and-ids', '09-options-results-and-matching',
    '10-importing-a-har', '11-drawing-and-navigation', '12-grouping-requests',
    '13-following-redirects', '14-recognizing-repeats', '15-reading-protocol-labels',
    '16-preparing-a-request', '17-waiting-for-a-response', '24-sharing-work',
    '18-comparing-responses', '19-submitting-text', '21-moving-through-text',
    '25-reading-event-streams', '26-switching-protocols', '27-observing-live-events',
    '28-sharing-a-connection', '29-reading-packet-bytes', '30-putting-bytes-in-order',
    '31-finding-http-boundaries', '32-reading-signaling', '33-interpreting-a-trace',
    '20-remembering-a-request', '23-shaping-the-program', '04-quality-and-tests',
]


def questions(level):
    """Return (title, tags, text) for each question on one bank page."""
    text = (DOCS / 'questions' / f'{level}.md').read_text()
    blocks = re.split(r'^(?=### )', text, flags=re.MULTILINE)[1:]
    result = []
    for block in blocks:
        block = re.split(r'^(?=## )', block, flags=re.MULTILINE)[0].rstrip()
        title = block.splitlines()[0][4:].strip()
        tag = TAG.search(block)
        tags = [t.strip() for t in tag[1].split(',')] if tag else []
        result.append((title, tags, block))
    return result


def selection(slug, bank):
    """Pick up to MAX_QUESTIONS for a chapter, alternating between levels."""
    pools = [[q for q in bank[level] if slug in q[1]] for level in LEVELS]
    chosen = []
    while len(chosen) < MAX_QUESTIONS and any(pools):
        for pool in pools:
            if pool and len(chosen) < MAX_QUESTIONS:
                chosen.append(pool.pop(0))
    return chosen


def section(chosen):
    parts = [
        MARKER,
        '## Check your understanding',
        'These questions come from the question bank '
        '([newcomer](../questions/newcomer.md), [practitioner](../questions/practitioner.md), '
        '[expert](../questions/expert.md)). Answer each one before you open its answer.',
    ]
    for _, _, block in chosen:
        parts.append(TAG.sub('', block).replace('\n\n\n', '\n\n').strip())
    return '\n\n'.join(parts) + '\n'


def expected(path, bank):
    text = path.read_text()
    body = text.split(MARKER)[0].rstrip() + '\n'
    return body + '\n' + section(selection(path.stem, bank))


def bank():
    return {level: questions(level) for level in LEVELS}


def main():
    loaded = bank()
    for slug in TEACHING:
        path = DOCS / 'chapters' / f'{slug}.md'
        path.write_text(expected(path, loaded))
        count = len(selection(slug, loaded))
        note = '' if count >= MIN_QUESTIONS else f'  (fewer than {MIN_QUESTIONS})'
        print(f'{slug}: {count} questions{note}')


if __name__ == '__main__':
    sys.exit(main())
